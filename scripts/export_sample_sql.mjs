// Dumps the seeded dataset as a MySQL INSERT script (database/sample_data.sql).
// Dates are written relative to CURDATE()/NOW() so "last 7 days" reports always return rows.
// Usage: node scripts/export_sample_sql.mjs
import fs from "node:fs";
import pg from "pg";

const client = new pg.Client({ connectionString: process.env.DATABASE_URL || "postgresql://postgres:postgres@127.0.0.1:5432/app_db" });
await client.connect();
const rows = async (sql) => (await client.query(sql)).rows;

const S = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/\\/g, "\\\\").replace(/'/g, "''")}'`);
const N = (v) => (v === null || v === undefined ? "NULL" : String(v));
const D = (d) => (Number(d) === 0 ? "CURDATE()" : `CURDATE() - INTERVAL ${Number(d)} DAY`);
const T = (d, t) => `TIMESTAMP(${D(d)}, '${t}')`;

function block(table, cols, data, chunk = 40) {
  let out = `-- ${table}: ${data.length} rows\n`;
  for (let i = 0; i < data.length; i += chunk) {
    out += `INSERT INTO ${table} (${cols.join(", ")}) VALUES\n${data.slice(i, i + chunk).map((r) => `(${r.join(", ")})`).join(",\n")};\n`;
  }
  return out + "\n";
}

const patient = await rows("SELECT * FROM patient ORDER BY patient_id");
const med = await rows("SELECT *, (CURRENT_DATE - record_date) AS days_ago FROM medical_record ORDER BY record_id");
const sugar = await rows("SELECT *, (CURRENT_DATE - record_date::date) AS days_ago, to_char(record_date, 'HH24:MI:SS') AS t FROM blood_sugar_record ORDER BY sugar_record_id");
const lab = await rows("SELECT *, (CURRENT_DATE - report_date) AS days_ago FROM lab_report ORDER BY lab_id");
const meal = await rows("SELECT * FROM meal ORDER BY meal_id");
const mealRec = await rows("SELECT *, (CURRENT_DATE - meal_date) AS days_ago FROM meal_record ORDER BY meal_record_id");
const act = await rows("SELECT * FROM activity ORDER BY activity_id");
const actRec = await rows("SELECT *, (CURRENT_DATE - activity_date) AS days_ago FROM activity_record ORDER BY activity_record_id");
const pred = await rows("SELECT *, (CURRENT_DATE - prediction_date::date) AS days_ago, to_char(prediction_date, 'HH24:MI:SS') AS t FROM prediction ORDER BY prediction_id");
const reco = await rows("SELECT *, (CURRENT_DATE - recommendation_date) AS days_ago FROM recommendation ORDER BY recommendation_id");

let sql = `-- =====================================================================
--  Diabetes Patient Management and Lifestyle Recommendation System
--  SAMPLE DATA  (MySQL 8 syntax)  –  generated by scripts/export_sample_sql.mjs
--
--  ${patient.length} patients, ${med.length} medical records, ${sugar.length} glucose readings, ${lab.length} lab reports,
--  ${meal.length} meals, ${mealRec.length} meal records, ${act.length} activities, ${actRec.length} activity records,
--  ${pred.length} predictions, ${reco.length} recommendations.
--
--  All dates are relative to CURDATE()/NOW(), so trend and "last 7 days"
--  reports always return rows regardless of when the script is loaded.
--
--  Load:   mysql -u root -p diabetes_dbms < database/sample_data.sql
--     or:  POST http://localhost:8000/api/seed   (FastAPI backend)
-- =====================================================================
USE diabetes_dbms;

SET FOREIGN_KEY_CHECKS = 0;
TRUNCATE TABLE recommendation;
TRUNCATE TABLE prediction;
TRUNCATE TABLE activity_record;
TRUNCATE TABLE meal_record;
TRUNCATE TABLE lab_report;
TRUNCATE TABLE blood_sugar_record;
TRUNCATE TABLE medical_record;
TRUNCATE TABLE activity;
TRUNCATE TABLE meal;
TRUNCATE TABLE patient;
SET FOREIGN_KEY_CHECKS = 1;

START TRANSACTION;

`;
sql += block("patient", ["patient_id", "name", "age", "gender", "phone", "email", "height", "weight", "bmi"],
  patient.map((p) => [N(p.patient_id), S(p.name), N(p.age), S(p.gender), S(p.phone), S(p.email), N(p.height), N(p.weight), N(p.bmi)]));
sql += block("medical_record", ["record_id", "patient_id", "medical_history", "existing_conditions", "medications", "record_date"],
  med.map((r) => [N(r.record_id), N(r.patient_id), S(r.medical_history), S(r.existing_conditions), S(r.medications), D(r.days_ago)]));
sql += block("blood_sugar_record", ["sugar_record_id", "patient_id", "glucose_level", "measurement_type", "record_date"],
  sugar.map((r) => [N(r.sugar_record_id), N(r.patient_id), N(r.glucose_level), S(r.measurement_type), T(r.days_ago, r.t)]));
sql += block("lab_report", ["lab_id", "patient_id", "hba1c", "bp_systolic", "bp_diastolic", "report_date"],
  lab.map((r) => [N(r.lab_id), N(r.patient_id), N(r.hba1c), N(r.bp_systolic), N(r.bp_diastolic), D(r.days_ago)]));
sql += block("meal", ["meal_id", "meal_name", "meal_type", "calories", "carbohydrates", "description"],
  meal.map((m) => [N(m.meal_id), S(m.meal_name), S(m.meal_type), N(m.calories), N(m.carbohydrates), S(m.description)]));
sql += block("meal_record", ["meal_record_id", "patient_id", "meal_id", "meal_date", "status"],
  mealRec.map((r) => [N(r.meal_record_id), N(r.patient_id), N(r.meal_id), D(r.days_ago), S(r.status)]));
sql += block("activity", ["activity_id", "activity_name", "activity_type", "recommended_duration", "description"],
  act.map((a) => [N(a.activity_id), S(a.activity_name), S(a.activity_type), N(a.recommended_duration), S(a.description)]));
sql += block("activity_record", ["activity_record_id", "patient_id", "activity_id", "duration", "steps", "activity_date"],
  actRec.map((r) => [N(r.activity_record_id), N(r.patient_id), N(r.activity_id), N(r.duration), N(r.steps), D(r.days_ago)]));
sql += block("prediction", ["prediction_id", "patient_id", "risk_level", "risk_score", "remarks", "prediction_date"],
  pred.map((r) => [N(r.prediction_id), N(r.patient_id), S(r.risk_level), N(r.risk_score), S(r.remarks), T(r.days_ago, r.t)]));
sql += block("recommendation", ["recommendation_id", "patient_id", "recommendation_type", "recommendation_text", "recommendation_date"],
  reco.map((r) => [N(r.recommendation_id), N(r.patient_id), S(r.recommendation_type), S(r.recommendation_text), D(r.days_ago)]));
sql += "COMMIT;\n";

fs.writeFileSync("database/sample_data.sql", sql);
await client.end();
console.log(`database/sample_data.sql written (${sql.length} bytes)`);
